  static String of(
    String languageCode,
    String key, {
    Map<String, String>? params,
  }) {
    final code = languageCode.toLowerCase();
    final Map<String, String> m = code.startsWith('ja')
        ? _ja
        : code.startsWith('en')
            ? _en
            : code.startsWith('zh')
                ? _zh
                : _ko;
    var s = m[key] ?? _en[key] ?? _ko[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        s = s.replaceAll('{$k}', v);
      });
    }
    return s;
  }
