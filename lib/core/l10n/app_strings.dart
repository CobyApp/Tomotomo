  /// Every key/value for [languageCode]. Exposed so tests can assert the four
  /// blocks stay in sync — a key missing from one block silently falls back and
  /// ships the wrong language.
  static Map<String, String> all(String languageCode) {
    final code = languageCode.toLowerCase();
    if (code.startsWith('ja')) return _ja;
    if (code.startsWith('en')) return _en;
    if (code.startsWith('zh')) return _zh;
    return _ko;
  }

  static String of(
    String languageCode,
    String key, {
    Map<String, String>? params,
  }) {
    final code = languageCode.toLowerCase();
    final Map<String, String> m = code.startsWith('ja')
        ? _ja
        : code.startsWith('en')
            ? _en
            : code.startsWith('zh')
                ? _zh
                : _ko;
    var s = m[key] ?? _en[key] ?? _ko[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        s = s.replaceAll('{$k}', v);
      });
    }
    return s;
  }
